#!/usr/bin/env python3
"""Genera Resources/ThirdPartyNotices.txt con las licencias del software de terceros que va en la app.

Uso: scripts/generate-third-party-notices.py [--check]

Las versiones salen de Package.resolved y los textos de las copias que SwiftPM descarga en
.build/checkouts (hay que haber compilado antes). Lo que no viene como paquete, porque va dentro
de TDLib, tiene su texto en scripts/licenses/.

Con --check no escribe nada: sale con 1 si el archivo no coincide con lo que se generaría.
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "Resources" / "ThirdPartyNotices.txt"
CHECKOUTS = ROOT / ".build" / "checkouts"
EXTRA = ROOT / "scripts" / "licenses"
RULE = "=" * 78

# Paquetes que se enlazan en la app: identidad en Package.resolved, nombre visible, carpeta en
# .build/checkouts, tipo de licencia y archivos a incluir. swift-argument-parser no está: solo lo
# usa la herramienta de línea de comandos de WhisperKit, que no forma parte de SaySo.
PACKAGES = [
    ("grdb.swift", "GRDB.swift", "GRDB.swift", "MIT License", ["LICENSE"]),
    ("whisperkit", "WhisperKit (Argmax OSS)", "WhisperKit", "MIT License", ["LICENSE", "NOTICES"]),
    ("tdlibframework", "TDLibFramework", "TDLibFramework", "MIT License", ["LICENSE"]),
]

# Componentes compilados dentro de TDLibFramework.
BUNDLED = [
    ("TDLib", "https://github.com/tdlib/td", "Boost Software License 1.0",
     "Copyright Aliaksei Levin, Arseny Smirnov. Included in binary form through TDLibFramework.",
     "tdlib.txt"),
    ("zlib", "https://zlib.net", "zlib License",
     "Linked into TDLib.", "zlib.txt"),
    ("OpenSSL", "https://www.openssl.org", "Apache License 2.0",
     "Linked into TDLib. Copyright The OpenSSL Project Authors. The full text of the Apache License, "
     "Version 2.0 is reproduced above, in the WhisperKit notices.", None),
]


def build():
    pins = {p["identity"]: p for p in json.loads((ROOT / "Package.resolved").read_text())["pins"]}
    out = [
        "SaySo — Third-Party Notices",
        "",
        "SaySo includes the following third-party software. Each component is distributed under its",
        "own license, reproduced below. This file is generated by scripts/generate-third-party-notices.py.",
        "",
    ]
    for identity, name, folder, kind, files in PACKAGES:
        pin = pins.get(identity)
        if pin is None:
            sys.exit(f"{identity} no está en Package.resolved")
        version = pin["state"].get("version") or pin["state"].get("revision", "")[:12]
        out += [RULE, f"{name} {version}", pin["location"].removesuffix(".git"), kind, RULE, ""]
        for file in files:
            path = CHECKOUTS / folder / file
            if not path.exists():
                sys.exit(f"Falta {path}. Compila antes con «swift build».")
            out += [path.read_text().strip(), ""]
    for name, url, kind, note, file in BUNDLED:
        out += [RULE, name, url, kind, RULE, "", note, ""]
        if file:
            out += [(EXTRA / file).read_text().strip(), ""]
    return "\n".join(out).rstrip() + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            sys.exit("ThirdPartyNotices.txt no está al día. Ejecuta scripts/generate-third-party-notices.py.")
        print("ThirdPartyNotices.txt está al día.")
        return
    OUTPUT.write_text(text)
    print(f"Escrito {OUTPUT.relative_to(ROOT)} ({len(text.splitlines())} líneas)")


if __name__ == "__main__":
    main()
